-- PROPOSAL ONLY: review and run once to provision application accounts.
-- This migration is not applied automatically and contains no default account or password.
-- Password hashes are generated locally by PasswordHashGenerator; plaintext passwords are never stored.
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

CREATE TABLE app_users (
    user_id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    username         VARCHAR2(64 CHAR) NOT NULL,
    password_hash    VARCHAR2(255 CHAR) NOT NULL,
    role_code        VARCHAR2(16 CHAR) NOT NULL,
    active_flag      CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    created_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    password_changed_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

ALTER TABLE app_users ADD CONSTRAINT pk_app_users PRIMARY KEY (user_id);
ALTER TABLE app_users ADD CONSTRAINT uq_app_users_username UNIQUE (username);
ALTER TABLE app_users ADD CONSTRAINT ck_app_users_username_lower CHECK (username = LOWER(username));
ALTER TABLE app_users ADD CONSTRAINT ck_app_users_role CHECK (role_code IN ('ADMIN', 'READ_ONLY'));
ALTER TABLE app_users ADD CONSTRAINT ck_app_users_active CHECK (active_flag IN ('Y', 'N'));

