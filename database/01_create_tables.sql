-- Creates empty tables in the currently connected user's schema.
-- Run once, after 00_privilege_check.sql has been reviewed.
-- This script contains no destructive statements.
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

CREATE TABLE vendors (
    vendor_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    vendor_code     VARCHAR2(20 CHAR) NOT NULL,
    vendor_name     VARCHAR2(120 CHAR) NOT NULL,
    contact_name    VARCHAR2(100 CHAR),
    phone           VARCHAR2(30 CHAR),
    email           VARCHAR2(254 CHAR),
    active_flag     CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE mess_blocks (
    block_id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    block_code      VARCHAR2(20 CHAR) NOT NULL,
    block_name      VARCHAR2(100 CHAR) NOT NULL,
    active_flag     CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE ingredients (
    ingredient_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ingredient_code VARCHAR2(20 CHAR) NOT NULL,
    ingredient_name VARCHAR2(100 CHAR) NOT NULL,
    base_unit       VARCHAR2(10 CHAR) NOT NULL,
    active_flag     CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE purchase_orders (
    po_id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    po_number       VARCHAR2(30 CHAR) NOT NULL,
    vendor_id       NUMBER NOT NULL,
    block_id        NUMBER NOT NULL,
    ordered_at      DATE DEFAULT SYSDATE NOT NULL,
    expected_by     DATE,
    status          VARCHAR2(12 CHAR) DEFAULT 'OPEN' NOT NULL,
    approved_amount NUMBER(12,2) NOT NULL,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE purchase_order_items (
    po_item_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    po_id           NUMBER NOT NULL,
    ingredient_id   NUMBER NOT NULL,
    ordered_qty     NUMBER(12,3) NOT NULL,
    unit_price      NUMBER(12,2) NOT NULL,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE delivery_receipts (
    receipt_id              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    po_id                   NUMBER NOT NULL,
    invoice_reference       VARCHAR2(60 CHAR) NOT NULL,
    invoice_amount          NUMBER(12,2) NOT NULL,
    arrived_at              TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    verified_by             VARCHAR2(100 CHAR),
    verified_at             TIMESTAMP,
    inventory_processed_at  TIMESTAMP,
    notes                   VARCHAR2(500 CHAR),
    created_at              TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE delivery_receipt_items (
    receipt_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    receipt_id      NUMBER NOT NULL,
    po_id           NUMBER NOT NULL,
    po_item_id      NUMBER NOT NULL,
    received_qty    NUMBER(12,3) NOT NULL,
    accepted_qty    NUMBER(12,3) NOT NULL,
    rejected_qty    NUMBER(12,3) NOT NULL,
    notes           VARCHAR2(500 CHAR),
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE inventory_balances (
    block_id        NUMBER NOT NULL,
    ingredient_id   NUMBER NOT NULL,
    on_hand_qty     NUMBER(12,3) DEFAULT 0 NOT NULL,
    reorder_level   NUMBER(12,3) DEFAULT 0 NOT NULL,
    updated_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE inventory_transactions (
    transaction_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    transaction_reference VARCHAR2(50 CHAR) NOT NULL,
    block_id            NUMBER NOT NULL,
    ingredient_id       NUMBER NOT NULL,
    transaction_type    VARCHAR2(16 CHAR) NOT NULL,
    quantity_delta      NUMBER(12,3) NOT NULL,
    balance_after_qty   NUMBER(12,3) NOT NULL,
    source_receipt_item_id NUMBER,
    notes               VARCHAR2(500 CHAR),
    created_at          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE daily_mess_records (
    record_id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    block_id            NUMBER NOT NULL,
    record_date         DATE NOT NULL,
    meals_served        NUMBER(8,0) NOT NULL,
    prepared_kg         NUMBER(12,3),
    leftover_kg         NUMBER(12,3),
    measurement_method  VARCHAR2(200 CHAR),
    notes               VARCHAR2(500 CHAR),
    created_at          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE vendor_contract_rules (
    rule_id             NUMBER GENERATED BY DEFAULT AS IDENTITY,
    vendor_id           NUMBER NOT NULL,
    rule_code           VARCHAR2(30 CHAR) NOT NULL,
    rule_name           VARCHAR2(120 CHAR) NOT NULL,
    discrepancy_type    VARCHAR2(20 CHAR) NOT NULL,
    effective_from      DATE NOT NULL,
    effective_to        DATE,
    tolerance_percent   NUMBER(5,2) DEFAULT 0 NOT NULL,
    penalty_percent     NUMBER(5,2) NOT NULL,
    max_penalty         NUMBER(12,2),
    terms_text          VARCHAR2(1000 CHAR) NOT NULL,
    created_at          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE vendor_penalty_reviews (
    review_id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    po_id               NUMBER NOT NULL,
    rule_id             NUMBER NOT NULL,
    eligible_line_count NUMBER(5,0) NOT NULL,
    eligible_value      NUMBER(12,2) NOT NULL,
    proposed_amount     NUMBER(12,2) NOT NULL,
    approved_amount     NUMBER(12,2),
    calculation_basis   VARCHAR2(1000 CHAR) NOT NULL,
    status              VARCHAR2(10 CHAR) DEFAULT 'PROPOSED' NOT NULL,
    reviewed_by         VARCHAR2(100 CHAR),
    reviewed_at         TIMESTAMP,
    review_notes        VARCHAR2(500 CHAR),
    created_at          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE audit_log (
    audit_id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    table_name      VARCHAR2(30 CHAR) NOT NULL,
    record_key      VARCHAR2(100 CHAR) NOT NULL,
    operation_type  CHAR(1 CHAR) NOT NULL,
    changed_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    changed_by      VARCHAR2(128 CHAR) NOT NULL,
    old_values      CLOB,
    new_values      CLOB
);
